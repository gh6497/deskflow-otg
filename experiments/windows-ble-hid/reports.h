inline std::vector<uint8_t> map(bool keyboard_only)
{
    // Each descriptor begins with Usage Page, Usage, Collection. Inject Report
    // ID inside that application collection; HOGP values omit the ID byte.
    std::vector<uint8_t> result;
    auto append = [&result](const auto& desc, uint8_t id) {
        result.insert(result.end(), desc, desc + 6);
        result.insert(result.end(), {0x85, id});
        result.insert(result.end(), desc + 6, desc + sizeof(desc));
    };
    append(keyboard_desc, 1);
    if (!keyboard_only) append(pointer_desc, 2);
    return result;
}

inline std::array<uint8_t, 8> pointer(uint16_t x, uint16_t y,
    uint8_t flags = 2, uint8_t buttons = 0, int8_t wheel = 0, int8_t pan = 0)
{
    return {flags, buttons, static_cast<uint8_t>(x), static_cast<uint8_t>(x >> 8),
        static_cast<uint8_t>(y), static_cast<uint8_t>(y >> 8),
        static_cast<uint8_t>(wheel), static_cast<uint8_t>(pan)};
}
